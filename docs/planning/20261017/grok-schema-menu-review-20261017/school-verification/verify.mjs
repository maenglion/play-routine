import { PGlite } from '@electric-sql/pglite';
import { readFile, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const source=new URL('../School-Hierarchy-Recursive-Queries.sql', import.meta.url);
const db=new PGlite();
const checks=[];
const check=(name,fn)=>{fn();checks.push(name);};
const tree=async(at,root='PR-BASIC',family='demo-family')=>(await db.query('SELECT * FROM pg_temp.regulation_tree($1,$2,$3::timestamptz)',[family,root,at])).rows;
try {
 const sql=await readFile(source,'utf8');
 assert.match(sql,/ROLLBACK;\s*$/);
 const queryResults=await db.exec(sql.replace(/ROLLBACK;\s*$/,''));
 const before=await tree('2026-10-31T12:00:00+09:00');
 const after=await tree('2026-11-01T12:00:00+09:00');
 const old=before.find(x=>x.code==='PR-SCHOOL');
 const promoted=after.find(x=>x.code==='PR-SCHOOL');
 check('격상 전 School depth=2 / Task 관할',()=>{assert.equal(old.depth,2);assert.equal(old.parent_code,'PR-TASK');});
 check('격상 후 School depth=1 / 기본법 관할',()=>{assert.equal(promoted.depth,1);assert.equal(promoted.parent_code,'PR-BASIC');});
 check('규정 영구 ID 보존 / 버전만 v1→v2',()=>{assert.equal(old.regulation_id,promoted.regulation_id);assert.notEqual(old.regulation_version_id,promoted.regulation_version_id);});
 check('Task·Quest·Lifestyle·School 4개 동등 위계',()=>{assert.deepEqual(after.filter(x=>x.depth===1&&!x.is_cycle).map(x=>x.code).sort(),['PR-LIFESTYLE','PR-QUEST','PR-SCHOOL','PR-TASK']);});
 check('출결 규정 원문 버전 유지 / 전체 깊이만 3→2',()=>{const a=before.find(x=>x.code==='PR-SCHOOL-ATTENDANCE');const b=after.find(x=>x.code==='PR-SCHOOL-ATTENDANCE');assert.equal(a.regulation_version_id,b.regulation_version_id);assert.equal(a.depth,3);assert.equal(b.depth,2);});
 const sub=await tree('2026-11-01T12:00:00+09:00','PR-SCHOOL');
 check('School 기준 하위 출결 조회',()=>{assert.equal(sub.length,2);assert.equal(sub.find(x=>x.code==='PR-SCHOOL').depth,0);assert.equal(sub.find(x=>x.code==='PR-SCHOOL-ATTENDANCE').depth,1);});
 const justBefore=await tree('2026-10-31T23:59:59.999+09:00');
 const exact=await tree('2026-11-01T00:00:00+09:00');
 check('효력 구간 [from,to) 경계에 School 한 버전만',()=>{assert.equal(justBefore.filter(x=>x.code==='PR-SCHOOL').length,1);assert.equal(exact.filter(x=>x.code==='PR-SCHOOL').length,1);assert.equal(justBefore.find(x=>x.code==='PR-SCHOOL').version_no,1);assert.equal(exact.find(x=>x.code==='PR-SCHOOL').version_no,2);});
 const foreign=await tree('2026-11-01T12:00:00+09:00','PR-BASIC','other-family');
 check('다른 가족 조회에는 이 가족 자료 없음',()=>assert.equal(foreign.length,0));
 check('개정 REVISES 관계는 위계 탐색에서 제외',()=>{assert.equal(before.length,6);assert.equal(after.length,6);assert.ok(after.every(x=>!x.is_cycle));});
 await db.exec("INSERT INTO pg_temp.demo_regulation_version_relationships VALUES ('unapproved-edge','demo-family','school-v2','task-v1','GOVERNS',false,'미승인 테스트','2026-11-01 00:00+09',NULL)");
 const unapproved=await tree('2026-11-01T12:00:00+09:00');
 check('미승인 관계는 위계에서 제외',()=>assert.equal(unapproved.length,6));
 await db.exec("INSERT INTO pg_temp.demo_regulation_version_relationships VALUES ('cycle-test','demo-family','school-v2','basic-v1','GOVERNS',true,'검증용 순환','2026-11-01 00:00+09',NULL)");
 const cyclic=await tree('2026-11-01T12:00:00+09:00');
 check('CYCLE이 순환을 표시하고 재귀를 종료',()=>{assert.equal(cyclic.filter(x=>x.is_cycle).length,1);assert.ok(cyclic.length<20);});
 await db.exec('ROLLBACK');
 const cleanup=await db.query("SELECT to_regclass('pg_temp.demo_regulations')::text AS relation");
 check('ROLLBACK 뒤 임시 표가 남지 않음',()=>assert.equal(cleanup.rows[0].relation,null));
 const output={engine:'PGlite PostgreSQL',scope:'temporary SQL sample only; no Supabase or production access',checks,before,after,school_subtree:sub,sql_select_outputs:queryResults.filter(x=>x.rows?.length).map(x=>x.rows)};
 await writeFile(new URL('result.json', import.meta.url),JSON.stringify(output,null,2)+'\n');
 console.log('샘플 SQL 검증 통과:',checks.length,'개');
 console.log('격상 전:',old.path);console.log('격상 후:',promoted.path);
 console.log('실제 쿼리 결과: school-verification/result.json');
} finally{await db.close();}
